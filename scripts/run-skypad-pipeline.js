// Orchestrator: runs the full Skypad error pipeline in order.
//   1. npm run SkypadLogs:errors   -> test-results/SkypadLogs-Error-report.json (+ bugTitle)
//   2. node scripts/generate-bug-tc-input.js -> TC-Input/BugtoTC_Input_<ts>.md
//                                              + test-results/SkypadLogs-Error-report_TC.json
//                                              + test-results/error_Info/error_details_<ts>.md
//      (step 2 also applies the Error_Impact_Scoring.js severity to each error, and writes the
//       error_Info .md LAST, after the _TC.json is final)
//   3. npm run tc:generate      -> Excel test cases (from _TC.json) in test-results/TC-Output + C:\Temp
const { spawnSync } = require('child_process');
const fs = require('fs');
const path = require('path');

const repoRoot = path.resolve(__dirname, '..');
const errorInfoDir = path.join(repoRoot, 'test-results', 'error_Info');

const steps = [
  { name: 'Analyze Skypad errors + bugTitle', cmd: 'npm', args: ['run', 'SkypadLogs:errors'] },
  {
    name: 'Generate TC input .md + _TC.json + error_Info details .md',
    cmd: 'node',
    args: [path.join('scripts', 'generate-bug-tc-input.js')],
    // Fail the pipeline if the error_Info details file was not (re)generated by this step.
    verify: (startedAt) => {
      const files = fs.existsSync(errorInfoDir)
        ? fs.readdirSync(errorInfoDir).filter((f) => /^error_details_\d{12}\.md$/.test(f))
        : [];
      return files.some((f) => fs.statSync(path.join(errorInfoDir, f)).mtimeMs >= startedAt - 1000);
    },
  },
  { name: 'Generate test cases (Excel)', cmd: 'npm', args: ['run', 'tc:generate'] },
];

for (const [i, s] of steps.entries()) {
  console.log(`\n=== Step ${i + 1}/${steps.length}: ${s.name} ===`);
  const startedAt = Date.now();
  const r = spawnSync(s.cmd, s.args, { cwd: repoRoot, stdio: 'inherit', shell: process.platform === 'win32' });
  if (r.status !== 0) {
    console.error(`\nStep ${i + 1} failed (exit ${r.status}). Pipeline stopped.`);
    process.exit(r.status || 1);
  }
  if (s.verify && !s.verify(startedAt)) {
    console.error(`\nStep ${i + 1} finished but its expected output (error_Info/error_details_<ts>.md) was not created. Pipeline stopped.`);
    process.exit(1);
  }
}
console.log('\nPipeline complete.');
